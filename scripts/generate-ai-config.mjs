import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");

function readEnvFile(filePath) {
  if (!existsSync(filePath)) {
    return {};
  }

  const raw = readFileSync(filePath, "utf8");
  const lines = raw.split(/\r?\n/);
  const result = {};

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) {
      continue;
    }

    const idx = trimmed.indexOf("=");
    if (idx <= 0) {
      continue;
    }

    const key = trimmed.slice(0, idx).trim();
    const value = trimmed.slice(idx + 1).trim();
    result[key] = value;
  }

  return result;
}

const envPath = resolve(root, ".env");
const env = readEnvFile(envPath);

const groqApiKey = env.GROQ_API_KEY || "";
const groqWorkerUrl = env.GROQ_WORKER_URL || "";
const groqModel = env.GROQ_MODEL || "qwen/qwen3-32b";

// Enabled if either API key (dev) or worker URL (prod) is set
const isEnabled = !!(groqApiKey || groqWorkerUrl);

// Validation warnings
if (!isEnabled) {
  console.warn("⚠️  Warning: GROQ_API_KEY or GROQ_WORKER_URL not set in .env file. AI features will not work.");
  console.warn("   See .env.example for configuration options.");
} else if (groqApiKey && groqWorkerUrl) {
  console.warn("⚠️  Warning: Both GROQ_API_KEY and GROQ_WORKER_URL are set.");
  console.warn("   Only GROQ_WORKER_URL will be used (Cloudflare Worker takes precedence).");
  console.warn("   Clear GROQ_API_KEY if you want to hide the API key from the bundle.");
} else if (groqWorkerUrl) {
  console.log("✅ Using Cloudflare Worker proxy (secure - no API key in bundle)");
} else if (groqApiKey) {
  console.warn("⚠️  Using direct Groq API (development mode - API key will be in bundle!)");
  console.warn("   For production, set up Cloudflare Worker proxy. See workers/README.md");
}

const configContent = `// Auto-generated by scripts/generate-ai-config.mjs
// Do not edit manually

export const AI_CONFIG = {
  GROQ_API_KEY: "${groqApiKey}",
  GROQ_WORKER_URL: "${groqWorkerUrl}",
  GROQ_MODEL: "${groqModel}",
  ENABLED: ${isEnabled}
} as const;
`;

const outputDir = resolve(root, "src", "ai");
if (!existsSync(outputDir)) {
  mkdirSync(outputDir, { recursive: true });
}

const outputPath = resolve(outputDir, "config.ts");
writeFileSync(outputPath, configContent, "utf8");
console.log("Generated src/ai/config.ts");
